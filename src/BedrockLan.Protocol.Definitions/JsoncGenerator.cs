using System.Collections;
using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;

namespace BedrockLan.Protocol.Definitions;

/// <summary>
/// Writes a <see cref="ProtocolDefinition"/> as a protocol config (JSONC), with each [Doc] as a // comment. The
/// output is deterministic: packets in registration order, types in the order they're first used.
/// </summary>
public static class JsoncGenerator
{
    /// <summary>The format description at the top of every generated config.</summary>
    public const string FormatNotes = """
        // Bedrock LAN transfer protocol: the packets the minimal transfer server sends and the conversation it holds
        // with a client, from the first packet to the Transfer. Built into the library as the default; a newer copy can
        // be loaded at run time (ProtocolConfig.Parse) to follow game updates without a new build.
        //
        // GENERATED by tools/ProtocolGen from the C# definitions in src/BedrockLan.Protocol.Definitions. Change those
        // instead: building BedrockLan regenerates this file, and the publish workflow hosts the same output.
        //
        // Format (formatVersion 1). JSON with // and /* */ comments and trailing commas allowed.
        //
        // packets.<Name> = { "id": <packet id>, "body": [ <field>, ... ] }
        //   A field is an object with exactly one type key, holding its value, plus optional modifiers:
        //     { "<Type>": <value>, "since": <protocol>, "until": <protocol>, "optional": true, "count": "<Type>" }
        //   "since" is inclusive (protocol >= since); "until" is exclusive (protocol < until). A field without either is
        //   always written. Protocols newer than any cut-off get the newest layout.
        //   Primitive types: Byte, Bool, Int16LE, UInt16LE, Int32LE, Int32BE, UInt32LE, Int64LE, UInt64LE, FloatLE,
        //          VarInt32, VarUInt32, VarInt64, VarUInt64 (zig-zag for the signed ones), String (VarUInt32 length +
        //          UTF-8), Bytes (hex, spaces allowed), NetworkNbt (a tag tree: { "compound": { ... } }).
        //   Declared types: any type in "types" (Vec3, LevelSettings, ...). Its value is an object of its fields
        //          ({ "Vec3": { "x": 0, "y": 100, "z": 0 } }), an array of them in order ({ "Vec3": [0, 100, 0] }),
        //          or, for a one-field type, just that value.
        //   Array<Type>: a count, then the items. The count is a VarUInt32 unless the field says "count": "UInt32LE"
        //          (Mojang's docs: "No size compression"), UInt16LE, Byte, ...
        //   "optional": true marks a field [OPT] as in Mojang's docs: a presence bool, then the value if present.
        //          null means absent.
        //   Values: a literal, or a variable: "$name". Use "$$" to start a literal string with "$".
        //     $protocol         the client's protocol version
        //     $target.host      where the client is being sent ($target.port: its port)
        //     $worldName        TransferOptions.LoadingWorldName
        //     $offlineMessage   TransferOptions.OfflineMessage
        //     $spawnTimeout     TransferOptions.SpawnTimeout, in seconds
        //     $uuid.random      a new random UUID string each time it's written
        //     $timing           TransferOptions.Timing: "Immediate", "AfterResourcePacks" or "AfterSpawn"
        //     plus any variable a stage's "read" stores (e.g. $radius).
        //
        // types.<Name> = [ { "<Type>": "fieldName" }, ... ]  A type made of fields, written in order. Fields take the
        //   same modifiers as packet fields and can use other declared types. A name may appear twice when the two
        //   fields' protocol ranges don't overlap (a field whose type changed in some version).
        //
        // session = { "start": <stage>, "transferPacket": <packet>, "offlinePacket": <packet>,
        //             "compressionHeaderSince": <protocol>, "stages": { <name>: <stage>, ... } }
        //   A stage waits for one client packet:
        //     "expect": { "packet": <id>, "read": [ <read field>, ... ] }
        //   Its read fields are read in order from the packet body:
        //     { "<Type>": "$var" }                  store the value (types: Byte, Bool, UInt16LE, Int32LE, Int32BE,
        //                                           UInt32LE, VarInt32, VarUInt32, String)
        //     { "<Type>": "$var", "keep": true }    store it only if the variable has no value yet
        //     { "<Type>": "$var", "clamp": [1, 8] } store it clamped to [min, max]
        //     { "<Type>": 4 } or { "<Type>": [1, 3] } the value must be one of these, or the packet is ignored
        //   Other packets, and packets whose read doesn't match, are ignored; the stage keeps waiting.
        //   Then its "steps" run in order. Each step may have:
        //     "if": <condition>           skip the step unless it holds
        //     "log": "text"               debug log line
        //     "send": [ "Packet", ... ]   send packets (each in its own batch)
        //     "compression": true         compress every batch from now on (after this step's sends)
        //   and at most one ending, which stops the steps:
        //     "goto": "<stage>"           wait in that stage next
        //     "transfer": true            send transferPacket (offlinePacket if the destination is offline), then close
        //     "close": true               close without sending anything
        //   Steps that end without an ending leave the session waiting in the same stage.
        //   "timeout": { "seconds": <number or $var>, "steps": [ ... ] } runs those steps if the stage is still waiting
        //   after that long.
        //   Conditions: { "timing": "AfterSpawn" | [..] }, { "protocol": { "min": n, "max": n } } (both inclusive),
        //   { "targetOnline": true|false }, { "variable": { "$name": value | [..] } } (the variable is one of them),
        //   { "any": [..] }, { "all": [..] }, { "not": {..} }.
        """;

    public static string Generate(ProtocolDefinition definition)
    {
        var w = new Writer();
        foreach (var line in FormatNotes.Split('\n'))
        {
            w.Line(line.TrimEnd('\r'));
        }

        w.Line("{");
        w.Indent++;
        w.Line($"\"formatVersion\": {definition.FormatVersion},");
        w.Line($"\"configVersion\": {Json(definition.ConfigVersion)},");
        w.Line();

        // Types, in the order they're first used by the packets.
        var types = new List<Type>();
        foreach (var (_, packet) in definition.Packets)
        {
            CollectTypes(packet.GetType(), types);
        }

        w.Line("// Types used by the packets, named and laid out as in Mojang's bedrock-protocol-docs.");
        w.Line("\"types\": {");
        w.Indent++;
        foreach (var type in types)
        {
            Comment(w, Metadata.Doc(type));
            w.Line($"{Json(Metadata.TypeName(type))}: [");
            w.Indent++;
            foreach (var field in Metadata.Fields(type))
            {
                w.Line($"{{ {Json(field.TypeName)}: {Json(field.Name)}{Modifiers(field)} }},{Trailing(field.Doc)}");
            }

            w.Indent--;
            w.Line("],");
        }

        w.Indent--;
        w.Line("},");
        w.Line();

        w.Line("\"packets\": {");
        w.Indent++;
        foreach (var (name, packet) in definition.Packets)
        {
            var type = packet.GetType();
            Comment(w, Metadata.Doc(type));
            w.Line($"{Json(name)}: {{");
            w.Indent++;
            w.Line($"\"id\": {Metadata.PacketId(type)},");
            w.Line("\"body\": [");
            w.Indent++;
            foreach (var field in Metadata.Fields(type))
            {
                var value = Value(field, field.Property.GetValue(packet), w.Indent);
                w.Line($"{{ {Json(field.TypeName)}: {value}{Modifiers(field)} }},{Trailing(field.Doc ?? field.Name)}");
            }

            w.Indent--;
            w.Line("],");
            w.Indent--;
            w.Line("},");
        }

        w.Indent--;
        w.Line("},");
        w.Line();

        WriteSession(w, definition.Session);
        w.Indent--;
        w.Line("}");
        return w.ToString();
    }

    private static void CollectTypes(Type type, List<Type> types)
    {
        foreach (var field in Metadata.Fields(type))
        {
            var clr = Nullable.GetUnderlyingType(field.Property.PropertyType) ?? field.Property.PropertyType;
            var inner = field.Kind == FieldKind.Array ? field.ElementType! : clr;
            if (Metadata.IsDeclaredType(inner) && !types.Contains(inner))
            {
                types.Add(inner);
                CollectTypes(inner, types);
            }
        }
    }

    private static string Modifiers(FieldMeta field)
    {
        var sb = new StringBuilder();
        if (field.Since is { } since)
        {
            sb.Append($", \"since\": {since}");
        }

        if (field.Until is { } until)
        {
            sb.Append($", \"until\": {until}");
        }

        if (field.Optional)
        {
            sb.Append(", \"optional\": true");
        }

        if (field.Count is { } count)
        {
            sb.Append($", \"count\": {Json(count.ToString())}");
        }

        return sb.ToString();
    }

    // ---- Values ----

    private static string Value(FieldMeta field, object? value, int indent)
    {
        if (field.Variable is { } variable)
        {
            return Json("$" + variable);
        }

        if (value is null)
        {
            return field.Optional
                ? "null"
                : throw new InvalidOperationException($"{field.Property.DeclaringType!.Name}.{field.Property.Name} is null but not [Optional].");
        }

        return field.Kind switch
        {
            FieldKind.Primitive => Scalar(value),
            FieldKind.Nbt => Nbt((NbtTag)value),
            FieldKind.Struct => Struct(value, indent),
            FieldKind.Array => Array(field, (IEnumerable)value, indent),
            _ => throw new InvalidOperationException(),
        };
    }

    private static string Array(FieldMeta field, IEnumerable items, int indent)
    {
        var rendered = items.Cast<object?>()
            .Select(item => Metadata.IsDeclaredType(field.ElementType!) ? Struct(item!, indent + 1) : Scalar(item!))
            .ToList();
        return rendered.Count == 0 ? "[]" : $"[ {string.Join(", ", rendered)} ]";
    }

    /// <summary>A declared type's value: an object of all its fields (one key per name), on one line if it's small.</summary>
    private static string Struct(object value, int indent)
    {
        var fields = Metadata.Fields(value.GetType());
        var entries = new List<(string Key, string Value, string? Doc)>();
        foreach (var field in fields)
        {
            if (entries.Any(e => e.Key == field.Name))
            {
                continue; // a versioned duplicate: the first one carries the value
            }

            entries.Add((field.Name, Value(field, field.Property.GetValue(value), indent + 1), field.Doc));
        }

        var inline = entries.Count <= 4 && entries.All(e => e.Doc is null && !e.Value.Contains('\n') && !e.Value.StartsWith('{'));
        if (inline)
        {
            return "{ " + string.Join(", ", entries.Select(e => $"{Json(e.Key)}: {e.Value}")) + " }";
        }

        var pad = new string(' ', (indent + 1) * 2);
        var sb = new StringBuilder("{\n");
        foreach (var (key, v, doc) in entries)
        {
            sb.Append(pad).Append(Json(key)).Append(": ").Append(v).Append(',').Append(Trailing(doc)).Append('\n');
        }

        sb.Append(new string(' ', indent * 2)).Append('}');
        return sb.ToString();
    }

    private static string Scalar(object value) => value switch
    {
        bool b => b ? "true" : "false",
        string s => Json(s.StartsWith('$') ? "$" + s : s),
        byte[] bytes => Json(Convert.ToHexString(bytes)),
        float f => f.ToString("R", CultureInfo.InvariantCulture),
        double d => d.ToString("R", CultureInfo.InvariantCulture),
        Enum e => Convert.ToInt64(e, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture),
        IFormattable n => n.ToString(null, CultureInfo.InvariantCulture),
        _ => throw new InvalidOperationException($"Can't write {value.GetType().Name} as a scalar."),
    };

    private static string Nbt(NbtTag tag) => tag switch
    {
        NbtCompound c => "{ \"compound\": { " + string.Join(", ", c.Entries.Select(e => $"{Json(e.Name)}: {Nbt(e.Tag)}")) + (c.Entries.Count > 0 ? " } }" : "} }"),
        NbtList l => $"{{ \"list\": {{ \"of\": {Json(l.Of.ToString().ToLowerInvariant())}, \"items\": [{string.Join(", ", l.Items.Select(Nbt))}] }} }}",
        NbtString s => $"{{ \"string\": {Json(s.Value)} }}",
        NbtByte b => $"{{ \"byte\": {b.Value} }}",
        NbtShort s => $"{{ \"short\": {s.Value} }}",
        NbtInt i => $"{{ \"int\": {i.Value} }}",
        NbtLong l => $"{{ \"long\": {l.Value} }}",
        NbtFloat f => $"{{ \"float\": {f.Value.ToString("R", CultureInfo.InvariantCulture)} }}",
        _ => throw new InvalidOperationException(),
    };

    // ---- Session ----

    private static void WriteSession(Writer w, SessionDefinition session)
    {
        w.Line("\"session\": {");
        w.Indent++;
        w.Line($"\"start\": {Json(session.Start)},");
        w.Line($"\"transferPacket\": {Json(session.TransferPacket)},");
        w.Line($"\"offlinePacket\": {Json(session.OfflinePacket)},");
        w.Line($"\"compressionHeaderSince\": {session.CompressionHeaderSince},");
        w.Line();
        w.Line("\"stages\": {");
        w.Indent++;
        foreach (var stage in session.Stages)
        {
            Comment(w, stage.Doc);
            w.Line($"{Json(stage.Name)}: {{");
            w.Indent++;
            var read = stage.Read.Count == 0 ? "" : $", \"read\": [ {string.Join(", ", stage.Read.Select(Read))} ]";
            w.Line($"\"expect\": {{ \"packet\": {(int)stage.Expect}{read} }},");
            w.Line("\"steps\": [");
            w.Indent++;
            foreach (var step in stage.Steps)
            {
                Comment(w, step.Doc);
                w.Line(Step(step) + ",");
            }

            w.Indent--;
            w.Line("],");
            if (stage.Timeout is { } timeout)
            {
                var seconds = timeout.Seconds is string s ? Json(s) : Scalar(timeout.Seconds);
                w.Line("\"timeout\": {");
                w.Indent++;
                w.Line($"\"seconds\": {seconds},");
                w.Line("\"steps\": [");
                w.Indent++;
                foreach (var step in timeout.Steps)
                {
                    Comment(w, step.Doc);
                    w.Line(Step(step) + ",");
                }

                w.Indent--;
                w.Line("],");
                w.Indent--;
                w.Line("},");
            }

            w.Indent--;
            w.Line("},");
            w.Line();
        }

        w.Indent--;
        w.Line("},");
        w.Indent--;
        w.Line("},");
    }

    private static string Read(ReadDefinition read)
    {
        var key = Json(read.Wire.ToString());
        if (read.Variable is { } variable)
        {
            var keep = read.Keep ? ", \"keep\": true" : "";
            var clamp = read.ClampMin is { } min && read.ClampMax is { } max ? $", \"clamp\": [{min}, {max}]" : "";
            return $"{{ {key}: {Json("$" + variable)}{keep}{clamp} }}";
        }

        var match = read.Values!;
        return match.Count == 1 ? $"{{ {key}: {match[0]} }}" : $"{{ {key}: [{string.Join(", ", match)}] }}";
    }

    private static string Step(StepDefinition step)
    {
        var parts = new List<string>();
        if (step.If is { } condition)
        {
            parts.Add($"\"if\": {Condition(condition)}");
        }

        if (step.Log is { } log)
        {
            parts.Add($"\"log\": {Json(log)}");
        }

        if (step.Send.Count > 0)
        {
            parts.Add($"\"send\": [ {string.Join(", ", step.Send.Select(Json))} ]");
        }

        if (step.Compression)
        {
            parts.Add("\"compression\": true");
        }

        if (step.Goto is { } target)
        {
            parts.Add($"\"goto\": {Json(target)}");
        }

        if (step.Transfer)
        {
            parts.Add("\"transfer\": true");
        }

        if (step.Close)
        {
            parts.Add("\"close\": true");
        }

        return "{ " + string.Join(", ", parts) + " }";
    }

    private static string Condition(Condition condition) => condition switch
    {
        TimingCondition t => t.Timings.Count == 1
            ? $"{{ \"timing\": {Json(t.Timings[0].ToString())} }}"
            : $"{{ \"timing\": [{string.Join(", ", t.Timings.Select(x => Json(x.ToString())))}] }}",
        ProtocolCondition p => "{ \"protocol\": { " + string.Join(", ", new[]
        {
            p.Min is { } min ? $"\"min\": {min}" : null,
            p.Max is { } max ? $"\"max\": {max}" : null,
        }.Where(x => x is not null)) + " } }",
        TargetOnlineCondition o => $"{{ \"targetOnline\": {(o.Online ? "true" : "false")} }}",
        AnyCondition a => $"{{ \"any\": [ {string.Join(", ", a.Conditions.Select(Condition))} ] }}",
        AllCondition a => $"{{ \"all\": [ {string.Join(", ", a.Conditions.Select(Condition))} ] }}",
        NotCondition n => $"{{ \"not\": {Condition(n.Condition)} }}",
        VariableCondition v => v.Values.Count == 1
            ? $"{{ \"variable\": {{ {Json("$" + v.Name)}: {Scalar(v.Values[0])} }} }}"
            : $"{{ \"variable\": {{ {Json("$" + v.Name)}: [{string.Join(", ", v.Values.Select(Scalar))}] }} }}",
        _ => throw new InvalidOperationException(),
    };

    // ---- Text helpers ----

    private static readonly JsonSerializerOptions JsonText = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    private static string Json(string text) => JsonSerializer.Serialize(text, JsonText);

    private static void Comment(Writer w, string? doc)
    {
        if (doc is null)
        {
            return;
        }

        foreach (var line in doc.Split('\n'))
        {
            w.Line("// " + line.Trim());
        }
    }

    private static string Trailing(string? doc) => doc is null || doc.Contains('\n') ? "" : " // " + doc;

    private sealed class Writer
    {
        private readonly StringBuilder _sb = new();

        public int Indent { get; set; }

        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                // Multi-line values (struct values) carry their own indentation after the first line.
                _sb.Append(' ', Indent * 2);
            }

            _sb.Append(text).Append('\n');
        }

        public override string ToString() => _sb.ToString();
    }
}
